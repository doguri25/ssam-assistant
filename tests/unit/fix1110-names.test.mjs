// 2026-11-10 검토 고침 — 「쌤」 채팅 이름 가리기(C1·M3): 이름 목록에 없는 이름 + 사람 조사(이·가·는·랑·한테·에게·하고·의),
// 홀로 쓴 이름 + 메모 말(발표·결석 …), 성 없는 이름(「지호가」「지우가」「민준이 오늘」「시우 학생」), 행특 메모는 더 넓게(을·를·과도) —
// 흔한 성 글자로 시작하는 낱말(구구단을·모둠원과·마무리를·한국사를·고무줄을·조각품을 …)과 낱말 같은 이름(하나·미소·우주 …)은 그대로.
import test from 'node:test';
import assert from 'node:assert/strict';
import { maskPersons } from '../../web/core/chat-names.js';
import { maskMemo } from '../../web/core/chat-route.js';

const masks = (t, name, out) => {
  const r = maskPersons(t);
  assert.ok(r.masked >= 1 && !r.text.includes(name), `${t} → ${r.text}`);
  if (out) assert.equal(r.text, out, t);
};
const keeps = t => assert.deepEqual(maskPersons(t), { text: t, masked: 0 }, t);

test('C1 목록 밖 이름 + 사람 조사(이·가·는·은·랑·한테·에게·하고·의)는 ○○○', () => {
  for (const [t, name, out] of [
    ['김다빈이 발표를 잘함', '김다빈', '○○○이 발표를 잘함'], ['최윤슬이 결석함', '최윤슬', '○○○이 결석함'], ['이건호가 친구를 도와줌', '이건호', '○○○가 친구를 도와줌'],
    ['조예담이 울었음', '조예담', '○○○이 울었음'], ['서이든이 조퇴함', '서이든', '○○○이 조퇴함'], ['오세린이 상장 받음', '오세린', '○○○이 상장 받음'],
    ['김라엘이 지각', '김라엘', '○○○이 지각'], ['권나윤이 발표', '권나윤', '○○○이 발표'], ['김다빈은 성실함', '김다빈', '○○○은 성실함'],
    ['최윤슬한테 전해 줘', '최윤슬', '○○○한테 전해 줘'], ['조예담에게 알림', '조예담', '○○○에게 알림'], ['이건호하고 다툼', '이건호', '○○○하고 다툼'],
    ['권나윤의 보호자', '권나윤', '○○○의 보호자'], ['오세린랑 짝', '오세린', '○○○랑 짝'], ['서이든이가 아픔', '서이든', '○○○이가 아픔']]) masks(t, name, out);
});

