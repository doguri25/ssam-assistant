test('C1 안내 글(chat-knowledge): 이름은 「되도록」 가린다고(다 가린다고 하지 않음), 학생은 이름 대신 번호로 쓰라고', async () => {
  const { GUIDE } = await import('../../web/core/chat-knowledge.js');
  const by = id => GUIDE.find(g => g.id === id).text;
  for (const id of ['chat', 'memo', 'privacy']) {
    assert.ok(/되도록/.test(by(id)) && /번호/.test(by(id)), `${id}: ${by(id)}`);
    assert.ok(!/학생 이름은 저장하지도 AI로 보내지도 않아요/.test(by(id)), `${id}: 단정`);
  }
  assert.ok(/다 가리지 못할 수/.test(by('privacy')), by('privacy'));
});
