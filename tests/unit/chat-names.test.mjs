test('이름 목록: 흔한 낱말과 겹치는 이름(정한·해진·어진·대한·정원·연수·이나·이든)은 넣지 않음', () => {
  for (const n of ['민준', '서연', '지훈', '하은', '철수', '영희', '가람', '나래', '하늘', '다솜']) assert.ok(GIVEN.has(n), n);
  for (const n of ['정한', '해진', '어진', '대한', '정원', '연수', '이나', '이든', '하진', '성원', '진주']) assert.ok(!GIVEN.has(n), n);
});

test('메모(maskMemo)·기록(safeText)·넘길 글(handoffText)', () => {
  assert.deepEqual(maskMemo('김민수가 토론에서 근거 들어 반론 잘함'), { text: '○○○가 토론에서 근거 들어 반론 잘함', masked: 1, dropped: 0 });
  assert.deepEqual(maskMemo('민준이가 구구단을 다 외움'), { text: '○○○가 구구단을 다 외움', masked: 1, dropped: 0 });
  for (const t of ['구구단을 외움', '모둠원과 협력함', '마무리를 잘함', '한국사를 좋아함', '고무줄을 가지고 놂', '조각품을 만듦']) assert.equal(maskMemo(t).masked, 0, t);
  assert.equal(safeText('박지훈 결석계 가정통신문\n문의 010-1234-5678'), '○○○ 결석계 가정통신문\n문의 ○○○');
  // 넘길 글: 줄·띄어쓰기는 그대로, 전화번호·전자 우편·이름만 그 자리에서
  assert.equal(handoffText('박지훈 결석계 가정통신문'), '○○○ 결석계 가정통신문');
  assert.equal(handoffText('공문 처리\n제목: 2026 과학의 날 운영 안내\n담당: 교무부장 (031-123-4567)'), '공문 처리\n제목: 2026 과학의 날 운영 안내\n담당: 교무부장 (○○○)');
  assert.equal(handoffText('알코올램프 10개 5,000원\n고무줄 20개  3,000원'), '알코올램프 10개 5,000원\n고무줄 20개  3,000원');
  assert.equal(handoffText('김민수 엄마한테 쪽지: ssam@school.kr로 회신'), '○○○ 엄마한테 쪽지: ○○○로 회신');
});
