const masks = (t, name, out) => {
  const r = maskPersons(t);
  assert.ok(r.masked >= 1 && !r.text.includes(name), `${t} → ${r.text}`);
  if (out) assert.equal(r.text, out, t);
};
const keeps = t => assert.deepEqual(maskPersons(t), { text: t, masked: 0 }, t);

