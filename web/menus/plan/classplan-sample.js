/* 한글 문서(제목·블록)를 앱이 한글 파일에서 읽은 것과 같은 글로 (표는 칸을 ' | '로) */
export const docText = doc => [doc.title, ...doc.blocks.map(b => (b.type === 'table' ? b.rows.map(r => r.join(' | ')).join('\n') : b.text))].join('\n');

const h = text => ({ type: 'h', text }), p = text => ({ type: 'p', text }), table = rows => ({ type: 'table', head: true, rows });

